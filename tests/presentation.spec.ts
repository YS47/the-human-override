import { expect, test } from '@playwright/test'

const heading = (title: RegExp) => ({ name: title, level: 1 })

test('moves forward and backward with a presenter remote and chapter links', async ({ page }) => {
  await page.goto('./')
  await expect(page.getByRole('heading', heading(/the human override/i))).toBeVisible()
  await expect(page.getByRole('button', { name: /begin/i })).toBeVisible()
  await page.keyboard.press('Space')
  await expect(page.getByRole('heading', heading(/two armies/i))).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(page).toHaveURL(/#scene-1.1-find$/)
  await page.getByRole('button', { name: 'Go to NGC2: The Connected Battlefield' }).click()
  await expect(page.getByRole('heading', heading(/connected/i))).toBeVisible()
  await page.keyboard.press('Space')
  await expect(page).toHaveURL(/#scene-1.3$/)
  await page.keyboard.press('ArrowLeft')
  await expect(page).toHaveURL(/#scene-1.2$/)
  await page.goBack()
  await expect(page).toHaveURL(/#scene-1.3$/)
  await page.getByRole('button', { name: 'Chapters', exact: true }).click()
  await page.getByRole('button', { name: /Who Pulled the Trigger/ }).last().click()
  await expect(page.getByRole('heading', heading(/will ai kill/i))).toBeVisible()
  await page.getByRole('button', { name: 'Go to Reflection' }).click()
  await expect(page.getByRole('heading', heading(/should we let it make that decision for us/i))).toBeVisible()
  await expect(page.getByRole('button', { name: 'Next scene', exact: true })).toBeDisabled()
})

